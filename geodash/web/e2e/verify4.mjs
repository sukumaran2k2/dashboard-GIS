import { chromium } from 'playwright-core';
import { readFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
const here = dirname(fileURLToPath(import.meta.url));
const BASE = process.env.GEODASH_URL ?? 'http://127.0.0.1:8765';
const SHOTS = join(here, '..', '.testdata', 'shots'); mkdirSync(SHOTS, { recursive: true });
const j = async (p, i) => { const r = await fetch(BASE + p, i); if (!r.ok) throw new Error(`${p} ${r.status} ${await r.text()}`); return r.json(); };
const pid = (await j('/api/projects', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'NEON real file' }) })).id;
const fd = new FormData(); fd.append('file', new Blob([readFileSync('C:\\Users\\sukus\\Downloads\\NEONDSSampleLiDARPointCloud.las')]), 'NEON.las');
const t0 = Date.now(); const ds = await j(`/api/projects/${pid}/upload`, { method: 'POST', body: fd });
console.log(`upload+ingest ${((Date.now() - t0) / 1000).toFixed(1)}s  points=${ds.meta.points.toLocaleString()}  crs=${ds.georef.crs}`);
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 860 } });
await ctx.addInitScript(() => { try { localStorage.setItem('geodash.basemap', 'none'); } catch {} });
const page = await ctx.newPage();
const errs = []; page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 150)); }); page.on('pageerror', (e) => errs.push(e.message.slice(0, 150)));
await page.goto(`${BASE}/#/dataset/${ds.id}`);
await page.waitForSelector('.viewer3d-hud'); await page.waitForFunction(() => !document.body.innerText.includes('Loading point cloud'), null, { timeout: 60000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: join(SHOTS, 'v4-neon-3d.png') });
await page.getByLabel('Top-down (orthographic)').check(); await page.waitForTimeout(1200);
await page.screenshot({ path: join(SHOTS, 'v4-neon-topdown.png') });
console.log('scale bar label:', await page.locator('.scale-bar-line').getAttribute('data-label'));
await page.getByRole('button', { name: 'Map footprint' }).click(); await page.waitForTimeout(3000);
await page.screenshot({ path: join(SHOTS, 'v4-neon-map.png') });
console.log('console errors:', errs.filter((e) => !/Failed to load resource/.test(e)));
await browser.close();
